//! Maven's remote repository filters: the `groupId` and `prefixes` rule
//! files maven-resolver reads to skip a repository for what it does not
//! serve, enabled by `aether.remoteRepositoryFilter.*` properties.
//!
//! Maven 3.9 (resolver 1.9) and Maven 3.10 (resolver 2.0) differ: 1.9
//! enables a filter only when its property is `true` and matches a groupId
//! exactly, 2.0 enables both filters by default, reads a groupId rule as
//! "this group and below" with `!` and `=` modifiers, and takes a prefixes
//! file only with its `## repository-prefixes/2.0` header. Resolver 2.0
//! also fetches a repository's own `.meta/prefixes.txt` when no local file
//! names it; raeva does not, so that repository is asked as if it had no
//! prefixes file. A rule file is looked up by the id of the repository that
//! receives the request, the mirror's when one serves it.

use std::collections::{BTreeMap, HashMap, HashSet};
use std::path::{Component, Path, PathBuf};

use rv_maven_types::{MavenMode, Sha1, Sha256};

use crate::{ConfigError, ConfigOrigin};

/// The prefix of every property the filters read.
pub const FILTER_PROPERTY_PREFIX: &str = "aether.remoteRepositoryFilter.";

/// The basedir, under the local repository, when none is set.
const DEFAULT_BASEDIR: &str = ".remoteRepositoryFilters";

/// More rule files than this in one basedir fail the load.
const MAX_RULE_FILES: usize = 1024;

const PREFIXES_MAGIC: &str = "## repository-prefixes/2.0";
const PREFIXES_LEGACY_MAGIC: &str = "# Prefix file generated by Sonatype Nexus";
const PREFIXES_UNSUPPORTED: &str = "@ unsupported";
const PREFIXES_MAX_ENTRIES: usize = 100_000;
const PREFIXES_MAX_LINE: usize = 250;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Kind {
    GroupId,
    Prefixes,
}

impl Kind {
    fn name(self) -> &'static str {
        match self {
            Self::GroupId => "groupId",
            Self::Prefixes => "prefixes",
        }
    }

    fn property(self) -> String {
        format!("{FILTER_PROPERTY_PREFIX}{}", self.name())
    }
}

/// The filters in effect for one build: the rule files of each enabled
/// filter, by the repository key in their names, and the filter properties.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct RepositoryFilters {
    mode: MavenMode,
    properties: BTreeMap<String, String>,
    /// The filter properties the requested settings.xml profiles set, but
    /// the basedirs, which settings profile activation may not see.
    profile_properties: BTreeMap<String, String>,
    group_id: Option<RuleFiles<GroupRules>>,
    prefixes: Option<RuleFiles<PrefixRules>>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
struct RuleFiles<T> {
    /// Rules and file digest, by the key between the file name's prefix
    /// and its `.txt`.
    by_key: BTreeMap<String, (Sha256, T)>,
}

impl<T> RuleFiles<T> {
    fn lookup(&self, keys: &[String]) -> Option<&T> {
        keys.iter()
            .find_map(|key| self.by_key.get(key).map(|(_, rules)| rules))
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
enum GroupRules {
    /// Resolver 1.9: the groupIds listed, matched exactly.
    Exact(HashSet<String>),
    /// Resolver 2.0: a tree of groupId elements.
    Tree(GroupNode),
}

#[derive(Debug, Clone, PartialEq, Eq)]
enum PrefixRules {
    Tree(PrefixNode),
    /// A resolver 2.0 prefixes file it rejects, which counts as no file.
    Rejected,
}

#[derive(Debug, Clone, Default, PartialEq, Eq)]
struct GroupNode {
    children: HashMap<String, GroupNode>,
    stop: bool,
    accept: Option<bool>,
}

#[derive(Debug, Clone, Default, PartialEq, Eq)]
struct PrefixNode {
    children: HashMap<String, PrefixNode>,
}

impl PrefixNode {
    fn insert<'a>(&mut self, elements: impl Iterator<Item = &'a str>) {
        let mut node = self;
        for element in elements {
            node = node.children.entry(element.to_string()).or_default();
        }
    }

    /// Whether the elements of `path` lead to a leaf, as `PrefixTree`
    /// decides it.
    fn accepts(&self, path: &str) -> bool {
        let mut node = self;
        for element in path_elements(path) {
            match node.children.get(element) {
                None => return false,
                Some(child) => {
                    node = child;
                    if node.children.is_empty() {
                        break;
                    }
                }
            }
        }
        node.children.is_empty()
    }
}

impl GroupNode {
    fn root() -> Self {
        Self {
            accept: Some(false),
            ..Self::default()
        }
    }

    /// `GroupTree.loadNode` for one line that is not a comment.
    fn load(&mut self, line: &str) -> Result<(), String> {
        let (accept, line) = match line.strip_prefix('!') {
            Some(rest) => (false, rest),
            None => (true, line),
        };
        let (stop, line) = match line.strip_prefix('=') {
            Some(rest) => (true, rest),
            None => (false, line),
        };
        if line == "*" {
            self.accept = Some(accept);
            return Ok(());
        }
        let elements: Vec<&str> = line.split('.').filter(|e| !e.is_empty()).collect();
        if elements.is_empty() {
            return Err(format!("rule {line:?} names no groupId"));
        }
        let mut node = self;
        for element in elements {
            node = node.children.entry(element.to_string()).or_default();
        }
        node.stop = stop;
        node.accept = Some(accept);
        Ok(())
    }

    /// `GroupTree.acceptedGroupId`.
    fn accepts(&self, group_id: &str) -> bool {
        let elements: Vec<&str> = group_id.split('.').filter(|e| !e.is_empty()).collect();
        let mut accepted = None;
        let mut node = self;
        for (index, element) in elements.iter().enumerate() {
            match node.children.get(*element) {
                None => break,
                Some(child) => {
                    node = child;
                    if node.stop && index + 1 == elements.len() {
                        accepted = node.accept;
                        break;
                    } else if !node.stop && node.accept.is_some() {
                        accepted = node.accept;
                    }
                }
            }
        }
        accepted.or(self.accept).unwrap_or(false)
    }
}

fn path_elements(path: &str) -> impl Iterator<Item = &str> {
    path.split('/').filter(|e| !e.is_empty())
}

/// Java's `String.trim`: strips the characters up to U+0020.
fn java_trim(line: &str) -> &str {
    line.trim_matches(|c: char| c <= ' ')
}

/// The lines of `text` as `BufferedReader.readLine` splits them.
fn java_lines(text: &str) -> Vec<&str> {
    let mut lines = Vec::new();
    let mut rest = text;
    while !rest.is_empty() {
        match rest.find(['\n', '\r']) {
            None => {
                lines.push(rest);
                break;
            }
            Some(end) => {
                lines.push(&rest[..end]);
                let skip = if rest[end..].starts_with("\r\n") {
                    2
                } else {
                    1
                };
                rest = &rest[end + skip..];
            }
        }
    }
    lines
}

fn is_rule(line: &str) -> bool {
    !line.starts_with('#') && !java_trim(line).is_empty()
}

/// Resolver 2.0's `PrefixesSource` checks, `None` for a file it rejects.
fn prefixes_v2_entries(text: Option<&str>) -> Option<Vec<String>> {
    let lines = java_lines(text?);
    let first = lines.first()?;
    if ![PREFIXES_MAGIC, PREFIXES_LEGACY_MAGIC, PREFIXES_UNSUPPORTED].contains(first) {
        return None;
    }
    let mut entries = Vec::new();
    for line in lines {
        let line = java_trim(line);
        if line == PREFIXES_UNSUPPORTED {
            return None;
        }
        if !line.starts_with('#') && !line.is_empty() {
            if line.len() > PREFIXES_MAX_LINE
                || !line.is_ascii()
                || line.contains([':', '<', '>', '\\'])
                || line.contains("//")
            {
                return None;
            }
            entries.push(line.trim_start_matches('.').to_string());
            if entries.len() > PREFIXES_MAX_ENTRIES {
                return None;
            }
        }
    }
    Some(entries)
}

/// Resolver 2.0's `PathUtils.stringToPathSegment`.
fn path_segment(id: &str) -> String {
    let mut segment = id.to_string();
    for (illegal, replacement) in [
        ("\\", "-BACKSLASH-"),
        ("/", "-SLASH-"),
        (":", "-COLON-"),
        ("\"", "-QUOTE-"),
        ("<", "-LT-"),
        (">", "-GT-"),
        ("|", "-PIPE-"),
        ("?", "-QMARK-"),
        ("*", "-ASTERISK-"),
    ] {
        segment = segment.replace(illegal, replacement);
    }
    match segment.as_str() {
        "." => "-DOT-".to_string(),
        ".." => "-DOTDOT-".to_string(),
        _ => segment,
    }
}

/// `Path.normalize`: drops `.` and folds `..` into the element before it.
fn normalize(path: &Path) -> PathBuf {
    let mut out = PathBuf::new();
    for component in path.components() {
        match component {
            Component::CurDir => {}
            Component::ParentDir => {
                if !out.pop() {
                    out.push(component);
                }
            }
            other => out.push(other),
        }
    }
    out
}

impl RepositoryFilters {
    /// The filters `properties` enable for a build in `mode`, with their
    /// rule files read from each filter's basedir: the `.basedir` property,
    /// taken from `local_repository` when relative, else
    /// `.remoteRepositoryFilters` there. `properties` holds the
    /// `aether.remoteRepositoryFilter.*` properties in effect; others are
    /// ignored.
    ///
    /// # Errors
    ///
    /// [`ConfigError::Invalid`] when a basedir is not a directory, holds more
    /// than 1024 rule files, or a rule file holds a rule resolver cannot
    /// load, and the read errors of [`crate::read_project_input`].
    pub fn load(
        mode: MavenMode,
        properties: BTreeMap<String, String>,
        local_repository: &Path,
    ) -> Result<Self, ConfigError> {
        let properties: BTreeMap<_, _> = (properties.into_iter())
            .filter(|(name, _)| name.starts_with(FILTER_PROPERTY_PREFIX))
            .collect();
        let mut filters = Self {
            mode,
            properties,
            profile_properties: BTreeMap::new(),
            group_id: None,
            prefixes: None,
        };
        for kind in [Kind::GroupId, Kind::Prefixes] {
            if !filters.enabled(kind) {
                continue;
            }
            let basedir = filters.basedir(kind, local_repository);
            let files = read_rule_files(kind, &basedir)?;
            match kind {
                Kind::GroupId => filters.group_id = Some(filters.group_rules(files)?),
                Kind::Prefixes => filters.prefixes = Some(filters.prefix_rules(files)?),
            }
        }
        Ok(filters)
    }

    /// [`Self::load`] from rule files given as `(kind, file name, bytes)`,
    /// `kind` being `groupId` or `prefixes`, rather than read from disk.
    ///
    /// # Errors
    ///
    /// As [`Self::load`] for the rules.
    #[cfg(any(test, feature = "testing"))]
    pub fn from_files(
        mode: MavenMode,
        properties: &[(&str, &str)],
        files: &[(&str, &str, &[u8])],
    ) -> Result<Self, ConfigError> {
        let mut filters = Self {
            mode,
            properties: (properties.iter())
                .map(|(name, value)| (name.to_string(), value.to_string()))
                .collect(),
            profile_properties: BTreeMap::new(),
            group_id: None,
            prefixes: None,
        };
        for kind in [Kind::GroupId, Kind::Prefixes] {
            if !filters.enabled(kind) {
                continue;
            }
            let prefix = format!("{}-", kind.name());
            let read = (files.iter())
                .filter(|(file_kind, _, _)| *file_kind == kind.name())
                .filter_map(|(_, name, bytes)| {
                    let key = name.strip_prefix(&prefix)?.strip_suffix(".txt")?;
                    Some((key.to_string(), PathBuf::from(name), bytes.to_vec()))
                })
                .collect();
            match kind {
                Kind::GroupId => filters.group_id = Some(filters.group_rules(read)?),
                Kind::Prefixes => filters.prefixes = Some(filters.prefix_rules(read)?),
            }
        }
        Ok(filters)
    }

    /// These filters with the properties of the settings.xml profiles the
    /// build requests, which [`Self::rule_input`] covers by value: Maven
    /// reads a profile `-P !id` turns off, which no settings property a
    /// model sees comes from.
    #[must_use]
    pub fn with_profile_properties(
        mut self,
        properties: impl IntoIterator<Item = (String, String)>,
    ) -> Self {
        self.profile_properties = (properties.into_iter())
            .filter(|(name, _)| {
                name.starts_with(FILTER_PROPERTY_PREFIX) && !name.ends_with(".basedir")
            })
            .collect();
        self
    }

    /// Whether some filter is enabled.
    pub fn is_active(&self) -> bool {
        self.group_id.is_some() || self.prefixes.is_some()
    }

    /// The filter properties in effect but the basedirs, which raeva.lock
    /// lists as user properties the resolution consults. A basedir only
    /// picks the rule files, which [`Self::rule_input`] covers, and its path
    /// differs between checkouts.
    pub fn property_names(&self) -> impl Iterator<Item = &str> {
        (self.properties.keys())
            .map(String::as_str)
            .filter(|name| !name.ends_with(".basedir"))
    }

    /// What the lock's configuration hash covers besides the values of the
    /// names it lists: the digest of each rule file an enabled filter read,
    /// by file name, each of [`Self::property_names`] that `listed`
    /// refuses, with its value, and the requested settings.xml profiles'
    /// filter properties. `None` when there is neither, so a build
    /// without filters keeps its hash.
    pub fn rule_input(&self, listed: impl Fn(&str) -> bool) -> Option<String> {
        let mut lines: Vec<String> = (self.property_names())
            .filter(|name| !listed(name))
            .map(|name| format!("property {name}={}", self.properties[name]))
            .collect();
        for (name, value) in &self.profile_properties {
            lines.push(format!("settings-property {name}={value}"));
        }
        if let Some(files) = &self.group_id {
            for (key, (digest, _)) in &files.by_key {
                lines.push(format!("file groupId-{key}.txt {digest}"));
            }
        }
        if let Some(files) = &self.prefixes {
            for (key, (digest, rules)) in &files.by_key {
                // What an ignored file holds changes no request.
                let digest = match rules {
                    PrefixRules::Rejected => "rejected".to_string(),
                    PrefixRules::Tree(_) => digest.to_string(),
                };
                lines.push(format!("file prefixes-{key}.txt {digest}"));
            }
        }
        (!lines.is_empty()).then(|| lines.join("\n"))
    }

    /// Why the filters keep the request for `path`, a file of `group_id`,
    /// from the repository `repository_id` at `repository_url`, which
    /// receives the request; `None` when they let it through.
    pub fn rejects(
        &self,
        repository_id: Option<&str>,
        repository_url: &str,
        group_id: &str,
        path: &str,
    ) -> Option<String> {
        if !self.is_active() {
            return None;
        }
        let id = repository_id.unwrap_or_default();
        let keys = match self.mode {
            MavenMode::Maven39 => vec![id.to_string()],
            MavenMode::Maven310 => {
                let sha1 = Sha1::from_bytes(repository_url.as_bytes());
                let segment = path_segment(id);
                vec![format!("{segment}-{}", sha1.as_str()), segment]
            }
        };
        if let Some(files) = &self.group_id
            && !self.group_accepts(files, &keys, id, group_id)
        {
            return Some(format!(
                "the groupId filter does not allow {group_id} from repository '{}'",
                rv_maven_types::bounded(id)
            ));
        }
        if let Some(files) = &self.prefixes
            && !self.prefix_accepts(files, &keys, id, path)
        {
            return Some(format!(
                "the prefixes filter does not allow {path} from repository '{}'",
                rv_maven_types::bounded(id)
            ));
        }
        None
    }

    fn group_accepts(
        &self,
        files: &RuleFiles<GroupRules>,
        keys: &[String],
        id: &str,
        group_id: &str,
    ) -> bool {
        if !self.repository_enabled(Kind::GroupId, id) {
            return true;
        }
        match files.lookup(keys) {
            Some(GroupRules::Exact(groups)) => groups.contains(group_id),
            Some(GroupRules::Tree(tree)) => tree.accepts(group_id),
            None => self.no_input_outcome(Kind::GroupId, id),
        }
    }

    fn prefix_accepts(
        &self,
        files: &RuleFiles<PrefixRules>,
        keys: &[String],
        id: &str,
        path: &str,
    ) -> bool {
        if !self.repository_enabled(Kind::Prefixes, id) {
            return true;
        }
        match files.lookup(keys) {
            Some(PrefixRules::Tree(tree)) => tree.accepts(path),
            Some(PrefixRules::Rejected) | None => self.no_input_outcome(Kind::Prefixes, id),
        }
    }

    /// `ConfigUtils.getBoolean`: the first of `keys` that is set, read as
    /// `Boolean.parseBoolean` reads it, else `default`.
    fn flag(&self, default: bool, keys: &[String]) -> bool {
        (keys.iter())
            .find_map(|key| self.properties.get(key))
            .map_or(default, |value| value.eq_ignore_ascii_case("true"))
    }

    fn enabled(&self, kind: Kind) -> bool {
        let base = kind.property();
        let default = self.mode == MavenMode::Maven310;
        let recording = kind == Kind::GroupId && self.flag(false, &[format!("{base}.record")]);
        self.flag(default, std::slice::from_ref(&base))
            && !self.flag(false, &[format!("{base}.skipped")])
            && !recording
    }

    /// Resolver 2.0's per-repository switches; 1.9 has none.
    fn repository_enabled(&self, kind: Kind, id: &str) -> bool {
        if self.mode == MavenMode::Maven39 {
            return true;
        }
        let base = kind.property();
        self.flag(true, &[format!("{base}.{id}"), format!("{base}.*")])
            && !self.flag(
                false,
                &[format!("{base}.skipped.{id}"), format!("{base}.skipped.*")],
            )
    }

    /// What a repository without a rule file gets: 1.9 lets every request
    /// through, 2.0 what `.noInputOutcome` says.
    fn no_input_outcome(&self, kind: Kind, id: &str) -> bool {
        if self.mode == MavenMode::Maven39 {
            return true;
        }
        let base = format!("{}.noInputOutcome", kind.property());
        self.flag(true, &[format!("{base}.{id}"), base])
    }

    fn basedir(&self, kind: Kind, local_repository: &Path) -> PathBuf {
        let name = (self.properties.get(&format!("{}.basedir", kind.property())))
            .map_or(DEFAULT_BASEDIR, String::as_str);
        let path = Path::new(name);
        if path.is_absolute() {
            normalize(path)
        } else {
            normalize(&local_repository.join(path))
        }
    }

    fn group_rules(
        &self,
        files: Vec<(String, PathBuf, Vec<u8>)>,
    ) -> Result<RuleFiles<GroupRules>, ConfigError> {
        let mut by_key = BTreeMap::new();
        for (key, path, bytes) in files {
            let digest = Sha256::from_bytes(&bytes);
            let text = std::str::from_utf8(&bytes)
                .map_err(|_| ConfigError::ProjectInputEncoding { path: path.clone() })?;
            let lines = java_lines(text).into_iter().filter(|line| is_rule(line));
            let rules = match self.mode {
                MavenMode::Maven39 => GroupRules::Exact(lines.map(str::to_string).collect()),
                MavenMode::Maven310 => {
                    let mut tree = GroupNode::root();
                    for line in lines {
                        tree.load(line).map_err(|message| ConfigError::Invalid {
                            origin: ConfigOrigin::MavenConfig(path.clone()),
                            message,
                        })?;
                    }
                    GroupRules::Tree(tree)
                }
            };
            by_key.insert(key, (digest, rules));
        }
        Ok(RuleFiles { by_key })
    }

    fn prefix_rules(
        &self,
        files: Vec<(String, PathBuf, Vec<u8>)>,
    ) -> Result<RuleFiles<PrefixRules>, ConfigError> {
        let mut by_key = BTreeMap::new();
        for (key, path, bytes) in files {
            let digest = Sha256::from_bytes(&bytes);
            let text = std::str::from_utf8(&bytes).ok();
            let rules = match self.mode {
                MavenMode::Maven39 => {
                    let text = text.ok_or(ConfigError::ProjectInputEncoding { path })?;
                    let mut tree = PrefixNode::default();
                    for line in java_lines(text).into_iter().filter(|line| is_rule(line)) {
                        tree.insert(path_elements(line));
                    }
                    PrefixRules::Tree(tree)
                }
                MavenMode::Maven310 => match prefixes_v2_entries(text) {
                    Some(entries) => {
                        let mut tree = PrefixNode::default();
                        for entry in entries.iter().filter(|line| is_rule(line)) {
                            tree.insert(path_elements(entry));
                        }
                        PrefixRules::Tree(tree)
                    }
                    None => {
                        tracing::warn!(
                            sec_code = "SETTING_IGNORED",
                            "ignoring {}: Maven 3.10 does not accept it as a prefixes file",
                            path.display()
                        );
                        PrefixRules::Rejected
                    }
                },
            };
            by_key.insert(key, (digest, rules));
        }
        Ok(RuleFiles { by_key })
    }
}

/// The `<kind>-*.txt` files in `basedir`, with the key their name gives and
/// their bytes. A missing basedir has none; a file that cannot be opened is
/// left out, as resolver leaves out one it cannot read.
fn read_rule_files(
    kind: Kind,
    basedir: &Path,
) -> Result<Vec<(String, PathBuf, Vec<u8>)>, ConfigError> {
    let invalid = |message: String| ConfigError::Invalid {
        origin: ConfigOrigin::MavenConfig(basedir.to_path_buf()),
        message,
    };
    let entries = match std::fs::read_dir(basedir) {
        Ok(entries) => entries,
        Err(_) if !basedir.exists() => return Ok(Vec::new()),
        Err(_) if !basedir.is_dir() => {
            return Err(invalid(format!(
                "the {} filter basedir is not a directory",
                kind.name()
            )));
        }
        Err(source) => {
            return Err(ConfigError::ProjectInputIo {
                path: basedir.to_path_buf(),
                source,
            });
        }
    };
    let prefix = format!("{}-", kind.name());
    let mut files = Vec::new();
    for entry in entries {
        let entry = entry.map_err(|source| ConfigError::ProjectInputIo {
            path: basedir.to_path_buf(),
            source,
        })?;
        let name = entry.file_name();
        let Some(key) = (name.to_str())
            .and_then(|name| name.strip_prefix(&prefix))
            .and_then(|name| name.strip_suffix(".txt"))
        else {
            continue;
        };
        let path = entry.path();
        if !path.is_file() {
            continue;
        }
        if files.len() == MAX_RULE_FILES {
            return Err(invalid(format!(
                "more than {MAX_RULE_FILES} {} filter files",
                kind.name()
            )));
        }
        match crate::read_project_input(&path) {
            Ok(bytes) => files.push((key.to_string(), path, bytes)),
            Err(ConfigError::ProjectInputIo { source, .. })
                if source.kind() == std::io::ErrorKind::PermissionDenied => {}
            Err(error) => return Err(error),
        }
    }
    Ok(files)
}

