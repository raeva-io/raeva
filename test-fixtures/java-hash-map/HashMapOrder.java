import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.SplittableRandom;

/**
 * Prints cases.txt: generated lists of strings and the order in which a
 * java.util.HashMap iterates them after they are put in list order, each
 * only if absent, as Maven's DefaultVersionRangeResolver puts the versions
 * it lists. The lists make bins collide so that the map resizes early,
 * treeifies, splits trees and untreeifies them.
 *
 *     java test-fixtures/java-hash-map/HashMapOrder.java > test-fixtures/java-hash-map/cases.txt
 */
public class HashMapOrder {
    static final String ALPHABET = "0123456789.-abcgrz";
    static final StringBuilder OUT = new StringBuilder();
    static final SplittableRandom RANDOM = new SplittableRandom(20261116);

    public static void main(String[] args) {
        OUT.append("# Generated by HashMapOrder.java on JDK ")
                .append(System.getProperty("java.version"))
                .append(". Each case lists keys and the\n")
                .append("# indices of the keys in the order a HashMap iterates them.\n");
        emit("range-ties", List.of(
                "1-ga-ga.ga.0-0.ga.ga", "1-ga-ga-0.ga-0.ga-0", "1-ga-ga-0.ga-0-0-0",
                "1-ga-ga-0-0-0.ga-0", "1-ga-ga-0-ga.ga.ga.ga", "1-ga-ga.0.ga.0.ga-ga",
                "1-ga-ga.0.0-ga-0.ga", "1-ga-ga.0-ga.ga.ga-ga", "1-ga-ga.0-ga.0-ga-0",
                "1-ga-ga-ga.ga-0-ga-ga", "1-ga-ga-ga.ga-ga.ga.ga"));
        for (int size : new int[] {1, 2, 12, 13, 24, 25, 48, 49, 97, 200}) {
            List<String> keys = noise(size);
            if (size > 12) {
                keys.add(keys.get(RANDOM.nextInt(keys.size())));
                keys.add(RANDOM.nextInt(keys.size()), keys.get(RANDOM.nextInt(keys.size())));
            }
            emit("random-" + size, keys);
        }
        // Every key has the same hash, so the tree orders them by compareTo.
        for (int size : new int[] {8, 9, 10, 11, 12, 16, 32}) {
            for (int noise : new int[] {0, 40}) {
                emit("same-hash-" + size + "-noise-" + noise, mix(sameHash(size), noise(noise)));
            }
        }
        // Keys whose spread hashes share their low bits share a bin until
        // the table outgrows those bits.
        for (int bits : new int[] {4, 6, 7}) {
            for (int colliding : new int[] {9, 12, 20, 40}) {
                for (int noise : new int[] {0, 50, 120}) {
                    emit("low-bits-" + bits + "-" + colliding + "-noise-" + noise,
                            mix(lowBits(bits, colliding), noise(noise)));
                }
            }
        }
        // A tree bin of 64 splits on bit 64 when the table grows to 128.
        for (int[] split : new int[][] {{14, 0}, {0, 14}, {7, 7}, {6, 6}, {7, 6}, {3, 11}, {11, 3}}) {
            List<String> keys = new ArrayList<>(splitBits(split[0], 0));
            keys.addAll(splitBits(split[1], 64));
            shuffle(keys);
            emit("split-" + split[0] + "-" + split[1], mix(keys, noise(90)));
        }
        // Pairs of equal hash that compareTo orders by UTF-16 unit, unlike
        // code point order, in one bin.
        for (int pairs : new int[] {5, 8, 12}) {
            for (int noise : new int[] {0, 60}) {
                emit("surrogates-" + pairs + "-noise-" + noise, mix(surrogatePairs(pairs), noise(noise)));
            }
        }
        System.out.print(OUT);
    }

    static void emit(String name, List<String> keys) {
        Map<String, Integer> map = new HashMap<>();
        for (int i = 0; i < keys.size(); i++) {
            if (!map.containsKey(keys.get(i))) {
                map.put(keys.get(i), i);
            }
        }
        OUT.append("## ").append(name).append('\n');
        OUT.append("keys: ").append(String.join(" ", keys)).append('\n');
        OUT.append("order:");
        for (int index : map.values()) {
            OUT.append(' ').append(index);
        }
        OUT.append('\n');
    }

    static int spread(String key) {
        int h = key.hashCode();
        return h ^ (h >>> 16);
    }

    static String word(int length) {
        StringBuilder word = new StringBuilder();
        for (int i = 0; i < length; i++) {
            word.append(ALPHABET.charAt(RANDOM.nextInt(ALPHABET.length())));
        }
        return word.toString();
    }

    static List<String> noise(int count) {
        List<String> keys = new ArrayList<>();
        for (int i = 0; i < count; i++) {
            keys.add(word(1 + RANDOM.nextInt(9)));
        }
        return keys;
    }

    static List<String> sameHash(int count) {
        List<String> keys = new ArrayList<>();
        for (int bits = 0; bits < 32 && keys.size() < count; bits++) {
            StringBuilder key = new StringBuilder("1-");
            for (int block = 0; block < 5; block++) {
                key.append((bits >> block & 1) == 0 ? "Aa" : "BB");
            }
            keys.add(key.toString());
        }
        shuffle(keys);
        return keys;
    }

    static List<String> lowBits(int bits, int count) {
        int mask = (1 << bits) - 1;
        int target = RANDOM.nextInt(1 << bits);
        List<String> keys = new ArrayList<>();
        while (keys.size() < count) {
            String key = "1." + word(1 + RANDOM.nextInt(6));
            if ((spread(key) & mask) == target && !keys.contains(key)) {
                keys.add(key);
            }
        }
        return keys;
    }

    static List<String> splitBits(int count, int bit) {
        List<String> keys = new ArrayList<>();
        while (keys.size() < count) {
            String key = "2." + word(1 + RANDOM.nextInt(6));
            if ((spread(key) & 127) == (5 | bit) && !keys.contains(key)) {
                keys.add(key);
            }
        }
        return keys;
    }

    // 961 * (0xE000 - 0xDBFF) == 31 * (0xDC00 - 0x5FE1), so for any prefix
    // the two keys share a hash, and the first, U+10FC00, sorts before U+E000
    // by UTF-16 unit.
    static List<String> surrogatePairs(int count) {
        List<String> keys = new ArrayList<>();
        int target = -1;
        while (keys.size() < 2 * count) {
            String prefix = "3." + word(1 + RANDOM.nextInt(6)) + "-";
            String low = prefix + "􏰀a";
            String high = prefix + "忡a";
            if (target < 0) {
                target = spread(low) & 63;
            }
            if ((spread(low) & 63) == target && !keys.contains(low)) {
                if (RANDOM.nextBoolean()) {
                    keys.add(low);
                    keys.add(high);
                } else {
                    keys.add(high);
                    keys.add(low);
                }
            }
        }
        return keys;
    }

    static List<String> mix(List<String> first, List<String> second) {
        List<String> keys = new ArrayList<>(first.size() + second.size());
        int i = 0, j = 0;
        while (i < first.size() || j < second.size()) {
            boolean takeFirst = j == second.size()
                    || (i < first.size() && RANDOM.nextInt(first.size() + second.size()) < first.size());
            keys.add(takeFirst ? first.get(i++) : second.get(j++));
        }
        return keys;
    }

    static void shuffle(List<String> keys) {
        for (int i = keys.size() - 1; i > 0; i--) {
            int j = RANDOM.nextInt(i + 1);
            String swap = keys.get(i);
            keys.set(i, keys.get(j));
            keys.set(j, swap);
        }
    }
}
