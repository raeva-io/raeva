#!/usr/bin/env bash
# The plugin gate: for each project in projects.tsv, check out its pinned
# commit, write its raeva.toml `[plugins]` table, run a cold `raeva sync`
# with an empty raeva home, `raeva export-m2` into an empty directory, and
# `mvn -o` on that directory alone with the network unshared. A project
# passes when Maven succeeds.
#
#   gate.sh <raeva-binary> <data-dir> [<name>...]
#
# Environment:
#   GATE_MVN       the mvn launcher (default: mvn on PATH), Maven 3.9.12
#   GATE_SETTINGS  the settings file raeva and Maven both read (default: none)
#   GATE_REPOS     a directory of clones named <owner>__<repo> to clone from
#                  instead of the network
#   GATE_JDK_ROOT  where the JDKs are, as java-<n>-openjdk (default /usr/lib/jvm)
#   GATE_SYNC_ARGS extra `raeva sync` arguments for every project
#   GATE_TRACE     1 sets `[plugins] trace` to the build's own Maven
#                  arguments; the trace runs `mvn` from PATH, where GATE_MVN's
#                  directory comes first
#   GATE_KEEP      1 keeps a passing project's checkout, store and m2
#
# netty's build needs cmake, a C compiler, cargo and patchelf on PATH.
#
# A project's prep script, when it names one, runs online before the sync and
# again before `mvn -o`, for what its build reads outside Maven. cargo keeps
# its crates in <data-dir>/<name>/cargo-home and runs offline under `mvn -o`.
#
# Writes <data-dir>/<name>/{sync,export,mvn}.log and a line per project to
# <data-dir>/results.tsv; exits 1 unless every selected project passes.
set -u
here=$(cd "$(dirname "$0")" && pwd)
raeva=$(realpath "${1:?raeva binary}")
data=$(realpath -m "${2:?data directory}")
shift 2
mvn=${GATE_MVN:-mvn}
jdk_root=${GATE_JDK_ROOT:-/usr/lib/jvm}
settings=()
[ -n "${GATE_SETTINGS:-}" ] && settings=(-s "$GATE_SETTINGS")
mkdir -p "$data"
results=$data/results.tsv
failed=0

checkout() { # <url> <commit> <dir>
  local url=$1 commit=$2 dir=$3 mirror
  mirror=${GATE_REPOS:+$GATE_REPOS/$(basename "$(dirname "$url")")__$(basename "$url" .git)}
  rm -rf "${dir:?}"
  git init -q "$dir"
  if [ -n "$mirror" ] && [ -d "$mirror" ] && git -C "$mirror" cat-file -e "$commit^{commit}" 2>/dev/null; then
    git -C "$dir" fetch -q --depth 1 "$mirror" "$commit"
  else
    git -C "$dir" fetch -q --depth 1 "$url" "$commit"
  fi
  git -C "$dir" -c advice.detachedHead=false checkout -q FETCH_HEAD || return 1
  rm -f "$dir/raeva.lock"
}

seconds() { echo "$(( $(date +%s) - $1 ))"; }

# The arguments as a TOML list of literal strings, which hold no quote.
toml_list() {
  local out='' arg
  for arg in "$@"; do
    case $arg in *"'"*) return 1 ;; esac
    out+="${out:+, }'$arg'"
  done
  printf '[%s]' "$out"
}

# The list is read on its own descriptor: a build reading stdin would eat it.
while IFS=$'\t' read -r name url commit jdk raeva_args mvn_args prep <&3; do
  case $name in '#'*|'') continue ;; esac
  if [ $# -gt 0 ] && ! printf '%s\n' "$@" | grep -qx "$name"; then continue; fi
  out=$data/$name
  rm -rf "${out:?}"
  mkdir -p "$out"
  src=$out/src
  if ! checkout "$url" "$commit" "$src"; then
    printf '%s\t%s\tfail at checkout\n' "$name" "$commit" | tee -a "$results"
    failed=1
    continue
  fi
  read -ra rargs <<< "$( [ "$raeva_args" = - ] || echo "$raeva_args")"
  read -ra margs <<< "$( [ "$mvn_args" = - ] || echo "$mvn_args")"
  read -ra extra <<< "${GATE_SYNC_ARGS:-}"
  java_home=$jdk_root/java-$jdk-openjdk
  export RAEVA_HOME=$out/raeva-home JAVA_HOME=$java_home CARGO_HOME=$out/cargo-home
  prepare() { [ "${prep:--}" = - ] || "$here/$prep" "$src" > "$out/prep.log" 2>&1; }
  step=prep start=$(date +%s)
  prepare
  rc=$?
  if [ $rc = 0 ]; then
    step=config
    # Apache RAT takes a file with this line for a generated one.
    plugins="# This file was generated by the raeva plugin gate."$'\n'
    plugins+="[plugins]"$'\n'"lock = true"$'\n'
    if [ "${GATE_TRACE:-}" = 1 ]; then
      trace=$(toml_list "${margs[@]}") || rc=1
      plugins+="trace = $trace"$'\n'"mvn = '$(basename "$mvn")'"$'\n'
    fi
    # The project's own settings would be overwritten.
    [ -e "$src/raeva.toml" ] && rc=1
    [ $rc = 0 ] && printf '%s' "$plugins" > "$src/raeva.toml"
  fi
  if [ $rc = 0 ]; then
    step=sync start=$(date +%s)
    launcher_dir=$(dirname "$mvn")
    [ "$launcher_dir" = . ] && launcher_dir=
    PATH=${launcher_dir:+$launcher_dir:}$java_home/bin:$PATH "$raeva" -C "$src" "${settings[@]}" sync "${rargs[@]}" "${extra[@]}" > "$out/sync.log" 2>&1
    rc=$?
  fi
  # The traced build leaves its output behind; `mvn -o` starts clean.
  if [ $rc = 0 ] && [ "${GATE_TRACE:-}" = 1 ]; then
    git -C "$src" clean -fdxq -e raeva.lock -e raeva.toml && prepare
    rc=$?
  fi
  sync_s=$(seconds "$start")
  if [ $rc = 0 ]; then
    step=export start=$(date +%s)
    "$raeva" -C "$src" "${settings[@]}" export-m2 --m2-path "$out/m2" "${rargs[@]}" > "$out/export.log" 2>&1
    rc=$?
  fi
  if [ $rc = 0 ]; then
    step=mvn start=$(date +%s)
    # Root in the namespace brings loopback up; the build runs as the user,
    # so tests of unreadable files see the permissions they expect.
    (cd "$src" && PATH=$java_home/bin:$PATH CARGO_NET_OFFLINE=true unshare -rn sh -c \
      'ip link set lo up && u=$1 g=$2 && shift 2 && exec unshare --map-user="$u" --map-group="$g" -- "$@"' sh "$(id -u)" "$(id -g)" \
      "$mvn" -B -o "${settings[@]}" -Dmaven.repo.local="$out/m2" "${margs[@]}") > "$out/mvn.log" 2>&1
    rc=$?
  fi
  missing=$(grep -c 'The POM for .* is missing' "$out/mvn.log" 2>/dev/null)
  if [ $rc = 0 ]; then verdict=pass; else verdict="fail at $step"; failed=1; fi
  printf '%s\t%s\t%s\tsync %ss\tmvn %ss\tmissing-pom-warnings %s\n' \
    "$name" "$commit" "$verdict" "$sync_s" "$(seconds "$start")" "${missing:-0}" | tee -a "$results"
  if [ "$verdict" = pass ] && [ -z "${GATE_KEEP:-}" ]; then
    rm -rf "${out:?}/src" "${out:?}/m2" "${out:?}/raeva-home" "${out:?}/cargo-home"
  else
    rm -rf "${src:?}/target"
  fi
done 3< "$here/projects.tsv" < /dev/null
exit $failed
